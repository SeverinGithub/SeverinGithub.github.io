#!/usr/bin/env node
// Builds the single-file game index.html from src/: shell.html + style.css + src/js/*.js in name order.
// The JS files share one scope (they are concatenated into one IIFE), so a later file may wrap a function of an earlier one.
//   node tools/build.mjs          -> index.html (+ syntax check, + src/INDEX.md)
//   node tools/build.mjs --test   -> also _t.html with the eval bridge window.__ev for browser tests
//   node tools/build.mjs --check  -> only verify that index.html is up to date with src/ (exit 1 if not)
import {readFileSync, writeFileSync, readdirSync, mkdtempSync, rmSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {tmpdir} from 'node:os';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src'), JS = join(SRC, 'js');
const args = new Set(process.argv.slice(2));

const files = readdirSync(JS).filter(f => /^\d{3}-[\w-]+\.js$/.test(f)).sort();
const js = files.map(f => readFileSync(join(JS, f), 'utf8')).join('');
const css = readFileSync(join(SRC, 'style.css'), 'utf8');
const shell = readFileSync(join(SRC, 'shell.html'), 'utf8');
if (!shell.includes('/*@CSS*/\n') || !shell.includes('//@JS\n')) throw new Error('shell.html: markers missing');
const html = shell.replace('/*@CSS*/\n', () => css).replace('//@JS\n', () => js);

const out = join(ROOT, 'index.html');
if (args.has('--check')) {
  const cur = readFileSync(out, 'utf8');
  if (cur !== html) { console.error('index.html is out of date: run node tools/build.mjs'); process.exit(1); }
  console.log('index.html is up to date'); process.exit(0);
}

// syntax check of the whole script before anything is written
const script = html.slice(html.indexOf('<script>') + 8, html.lastIndexOf('</script>'));
const tmp = mkdtempSync(join(tmpdir(), 'turm-'));
try {
  writeFileSync(join(tmp, 'game.js'), script);
  execFileSync(process.execPath, ['--check', join(tmp, 'game.js')], {stdio: 'pipe'});
} catch (e) {
  const msg = String(e.stderr || e.message);
  // map the line in the joined script back to a source file
  const m = msg.match(/game\.js:(\d+)/);
  if (m) {
    let line = +m[1] - (script.slice(0, script.indexOf("'use strict';")).split('\n').length);
    for (const f of files) { const n = readFileSync(join(JS, f), 'utf8').split('\n').length - 1; if (line <= n) { console.error(`syntax error in src/js/${f}:${line}`); break } line -= n; }
  }
  console.error(msg); process.exit(1);
} finally { rmSync(tmp, {recursive: true, force: true}); }

writeFileSync(out, html);
if (args.has('--test')) {
  const i = html.lastIndexOf('})();');
  writeFileSync(join(ROOT, '_t.html'), html.slice(0, i) + ';window.__ev=s=>eval(s);' + html.slice(i));
}

// INDEX.md: which file defines or wraps what, so nobody has to read the whole game to find a function
const defRe = /^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=/;
const wrapRe = /(?:^|;)\s*([A-Za-z_$][\w$]*)\s*=\s*function\b/g;
const lines = ['# Module index', '', 'Generated by `node tools/build.mjs` – do not edit. One line per file in load order: what it defines (top level) and which earlier functions it wraps (`↻`).', ''];
for (const f of files) {
  const src = readFileSync(join(JS, f), 'utf8'), defs = new Set(), wraps = new Set();
  const head = ((src.match(/^\/\* -+ (.*?)\*\//m) || [, ''])[1]).replace(/\s*-+\s*$/, '');
  for (const l of src.split('\n')) {
    const d = l.match(defRe); if (d) defs.add(d[1] || d[2]);
    for (const w of l.matchAll(wrapRe)) wraps.add(w[1]);
  }
  for (const d of defs) wraps.delete(d);
  const n = src.split('\n').length - 1;
  lines.push(`- **${f}** (${n} Z.) ${head ? '– ' + head : ''}`);
  if (defs.size) lines.push(`  - def: ${[...defs].filter(x => !x.startsWith('_')).join(', ')}`);
  if (wraps.size) lines.push(`  - ↻ ${[...wraps].join(', ')}`);
}
writeFileSync(join(SRC, 'INDEX.md'), lines.join('\n') + '\n');
console.log(`built index.html from ${files.length} modules (${(html.length / 1024).toFixed(0)} KB)` + (args.has('--test') ? ' + _t.html' : ''));

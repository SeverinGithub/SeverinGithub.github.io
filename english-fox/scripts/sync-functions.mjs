// Copies the shared checker code and the lesson content (incl. answer keys) into the
// Supabase function bundle. Run before `supabase functions deploy evaluate`.
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'

const out = new URL('../supabase/functions/_shared/', import.meta.url)
rmSync(new URL('content/', out), { recursive: true, force: true })
mkdirSync(new URL('content/', out), { recursive: true })
for (const f of ['types.ts', 'match.ts', 'fields.ts', 'errorTags.ts']) cpSync(new URL(`../shared/${f}`, import.meta.url), new URL(f, out))

const ids = readdirSync(new URL('../content/lessons/', import.meta.url)).map((f) => f.replace('.json', ''))
let src = '// generated by scripts/sync-functions.mjs – do not edit\n'
for (const id of ids) {
  cpSync(new URL(`../content/lessons/${id}.json`, import.meta.url), new URL(`content/lesson-${id}.json`, out))
  cpSync(new URL(`../content/solutions/${id}.json`, import.meta.url), new URL(`content/solution-${id}.json`, out))
  src += `import l_${id} from './lesson-${id}.json' with { type: 'json' }\nimport s_${id} from './solution-${id}.json' with { type: 'json' }\n`
}
src += `export const lessons: Record<string, unknown> = { ${ids.map((i) => `${i}: l_${i}`).join(', ')} }\n`
src += `export const solutions: Record<string, unknown> = { ${ids.map((i) => `${i}: s_${i}`).join(', ')} }\n`
writeFileSync(new URL('content/index.ts', out), src)
console.log(`synced ${ids.length} lessons`)
